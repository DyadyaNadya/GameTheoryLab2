import math
import pandas as pd
import matplotlib.pyplot as plt

# =====================================
# Исходные данные
# =====================================

k = 3          # число каналов
n = 12         # число источников
lam = 1.4      # интенсивность одного источника
t = 0.2        # часы

# =====================================
# Параметры системы
# =====================================

mu = 1 / t

# =====================================
# Предельные вероятности состояний
# =====================================

weights = [1.0]

for i in range(1, n + 1):

    lambda_prev = (n - (i - 1)) * lam
    mu_current = min(i, k) * mu

    weights.append(
        weights[-1]
        * lambda_prev
        / mu_current
    )

norm = sum(weights)

P = [w / norm for w in weights]

# =====================================
# Вероятность свободной системы
# =====================================

P0 = P[0]

# =====================================
# Среднее число заявок в системе
# =====================================

L = sum(
    i * P[i]
    for i in range(n + 1)
)

# =====================================
# Среднее число занятых каналов
# =====================================

busy = sum(
    min(i, k) * P[i]
    for i in range(n + 1)
)

# =====================================
# Среднее число свободных каналов
# =====================================

free = k - busy

# =====================================
# Среднее число заявок в очереди
# =====================================

Lq = sum(
    max(0, i - k) * P[i]
    for i in range(n + 1)
)

# =====================================
# Абсолютная пропускная способность
# =====================================

A = busy * mu

# =====================================
# Относительная пропускная способность
# =====================================

incoming = sum(
    (n - i) * lam * P[i]
    for i in range(n + 1)
)

Q = A / incoming

# =====================================
# Вероятность наличия очереди
# =====================================

P_queue = sum(
    P[i]
    for i in range(k + 1, n + 1)
)

# =====================================
# Временные характеристики
# =====================================

Wq = Lq / A
Wservice = 1 / mu
W = L / A

# =====================================
# Таблица состояний
# =====================================

df = pd.DataFrame({
    "Состояние": range(n + 1),
    "Вероятность": [round(x, 5) for x in P]
})

print("\nТаблица вероятностей состояний:")
print(df.to_string(index=False))

print("\nОсновные характеристики:")

print(f"Вероятность свободной системы: {P0:.3f}")
print(f"Среднее число заявок в очереди: {Lq:.3f}")
print(f"Среднее число заявок в системе: {L:.3f}")

print(f"Среднее число свободных каналов: {free:.3f}")
print(f"Среднее число занятых каналов: {busy:.3f}")

print(f"Абсолютная пропускная способность: {A:.3f}")
print(f"Относительная пропускная способность: {Q:.3f}")

print(f"Вероятность наличия очереди: {P_queue:.3f}")

print(f"Среднее время ожидания: {Wq:.3f} ч")
print(f"Среднее время обслуживания: {Wservice:.3f} ч")
print(f"Среднее время пребывания в системе: {W:.3f} ч")

# =====================================
# График вероятностей состояний
# =====================================

plt.figure(figsize=(10, 5))
plt.bar(range(n + 1), P)

plt.title("Предельные вероятности состояний")
plt.xlabel("Число заявок в системе")
plt.ylabel("Вероятность")

plt.grid(True)
plt.show()