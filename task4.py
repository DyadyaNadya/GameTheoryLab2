import math

# =====================================
# Исходные данные
# =====================================

lam = 0.8        # заявок в минуту
t = 2            # среднее время обслуживания (мин)
k = 3            # число каналов
omega = 8        # максимальное время ожидания (мин)
C = 200          # доход от одной обслуженной заявки
epsilon = 0.01  # требуемая точность

# =====================================
# Параметры системы
# =====================================

mu = 1 / t            # интенсивность обслуживания
theta = 1 / omega     # интенсивность ухода из очереди

# =====================================
# Предельные вероятности состояний
# =====================================

weights = [1.0]

i = 1

while True:

    if i <= k:
        coef = lam / (i * mu)
    else:
        coef = lam / (k * mu + (i - k) * theta)

    weights.append(weights[-1] * coef)

    # прекращаем вычисления,
    # когда очередное состояние становится пренебрежимо малым
    if weights[-1] < epsilon * 0.001:
        break

    i += 1

norm = sum(weights)

P = [w / norm for w in weights]

# =====================================
# Вероятность обслуживания
# =====================================

served_rate = 0

for state, prob in enumerate(P):

    if state <= k:
        served_rate += state * mu * prob
    else:
        served_rate += k * mu * prob

P_service = served_rate / lam

# =====================================
# Средние характеристики
# =====================================

Lq = 0
Lservice = 0

for state, prob in enumerate(P):

    if state > k:
        Lq += (state - k) * prob

    Lservice += min(state, k) * prob

L = Lq + Lservice

Wq = Lq / lam
W = L / lam

# Среднее время обслуживания
Wservice = 1 / mu

# =====================================
# Потери дохода
# =====================================

nu_leave = omega * Lq

losses = C * nu_leave

# =====================================
# Вывод результатов
# =====================================

print("\n" + "=" * 70)
print("СМО С ОГРАНИЧЕНИЕМ НА ВРЕМЯ ОЖИДАНИЯ")
print("=" * 70)

print("\nИсходные данные:")
print(f"λ = {lam} заявок/мин")
print(f"t = {t} мин")
print(f"k = {k}")
print(f"ω = {omega} мин")
print(f"C = {C}")
print(f"ε = {epsilon}")

print("\n" + "-" * 70)
print("ПРЕДЕЛЬНЫЕ ВЕРОЯТНОСТИ СОСТОЯНИЙ")
print("-" * 70)

for i, p in enumerate(P):
    print(f"P{i} = {p:.6f}")

print("\n" + "-" * 70)
print("ОСНОВНЫЕ ХАРАКТЕРИСТИКИ")
print("-" * 70)

print(f"Вероятность обслуживания заявки: {P_service:.6f}")

print(f"Среднее число заявок в очереди Lq: {Lq:.6f}")
print(f"Среднее число заявок под обслуживанием: {Lservice:.6f}")
print(f"Среднее число заявок в системе L: {L:.6f}")

print(f"\nСреднее время ожидания Wq: {Wq:.6f} мин")
print(f"Среднее время обслуживания: {Wservice:.6f} мин")
print(f"Среднее время пребывания в системе W: {W:.6f} мин")

print("\n" + "-" * 70)
print("ПОТЕРИ ДОХОДА")
print("-" * 70)

print(f"Интенсивность ухода ν_уход: {nu_leave:.6f}")
print(f"Потери дохода Д_потерь: {losses:.6f} у.е.")

print("\n" + "=" * 70)