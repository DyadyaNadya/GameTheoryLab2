import math
import pandas as pd
import matplotlib.pyplot as plt

# =====================================
# Исходные данные
# =====================================

n = 28          # число источников
k = 4           # общее число заявок за месяц
t = 2.0         # среднее время обслуживания (дни)
P_percent = 75  # требуемый процент исправных источников

# =====================================
# Параметры системы
# =====================================

# Общая интенсивность поступления заявок
lambda_total = k / 30

# Интенсивность поступления заявок от одного источника
lam = lambda_total / n

# Интенсивность обслуживания
mu = 1 / t

# =====================================
# Предельные вероятности состояний
# i — число неисправных источников
# =====================================

weights = [1.0]

for i in range(1, n + 1):

    coef = ((n - i + 1) * lam) / mu

    weights.append(weights[-1] * coef)

norm = sum(weights)

P = [w / norm for w in weights]

# =====================================
# Вероятность наличия не менее P%
# исправных источников
# =====================================

active_limit = math.ceil(n * P_percent / 100)

max_failed = n - active_limit

prob_active = sum(P[:max_failed + 1])

# =====================================
# Среднее число неисправных источников
# =====================================

L = sum(i * P[i] for i in range(n + 1))

# =====================================
# Абсолютная пропускная способность
# =====================================

A = mu * (1 - P[0])

# =====================================
# Среднее время ремонта и ожидания
# =====================================

W = L / A if A > 0 else 0

W_service = t
W_queue = max(0, W - W_service)

# =====================================
# Таблица вероятностей состояний
# =====================================

df_probs = pd.DataFrame({
    "Количество неисправных источников": range(n + 1),
    "Вероятность": [round(p, 5) for p in P]
})

# =====================================
# Вывод результатов
# =====================================

print("\n" + "=" * 70)
print("ЗАМКНУТАЯ ОДНОКАНАЛЬНАЯ СМО (СИСТЕМА ЭНГСЕТА)")
print("=" * 70)

print("\nИсходные данные:")
print(f"Количество источников: {n}")
print(f"Общее число заявок за месяц: {k}")
print(f"Среднее время обслуживания: {t} дней")
print(f"Требуемый процент исправных источников: {P_percent}%")

print("\nПромежуточные параметры:")
print(f"Общая интенсивность потока λ = {lambda_total:.5f} заявок/день")
print(f"Интенсивность от одного источника λ₁ = {lam:.5f} заявок/день")
print(f"Интенсивность обслуживания μ = {mu:.5f} обслуживаний/день")

print("\n" + "-" * 70)
print("ТАБЛИЦА ПРЕДЕЛЬНЫХ ВЕРОЯТНОСТЕЙ СОСТОЯНИЙ")
print("-" * 70)

print(df_probs.to_string(index=False))

print("\n" + "-" * 70)
print("ОСНОВНЫЕ ХАРАКТЕРИСТИКИ СИСТЕМЫ")
print("-" * 70)

print(
    f"Вероятность того, что исправно не менее "
    f"{P_percent}% источников: {prob_active:.3f}"
)

print(
    f"Среднее число неисправных источников: "
    f"{L:.3f}"
)

print(
    f"Абсолютная пропускная способность: "
    f"{A:.3f}"
)

print(
    f"Среднее время ремонта и ожидания ремонта: "
    f"{W:.3f} дней"
)

print(
    f"Среднее время ожидания ремонта: "
    f"{W_queue:.3f} дней"
)

print(
    f"Среднее время непосредственного ремонта: "
    f"{W_service:.3f} дней"
)

print("\n" + "-" * 70)
print("ИНТЕРПРЕТАЦИЯ РЕЗУЛЬТАТОВ")
print("-" * 70)

print(
    f"В среднем одновременно неисправно "
    f"{L:.3f} источников из {n}."
)

print(
    f"Вероятность сохранения не менее "
    f"{P_percent}% работоспособных источников "
    f"составляет {prob_active:.3f}."
)

print(
    f"Среднее время нахождения заявки в системе "
    f"составляет {W:.3f} дней."
)

print("\n" + "=" * 70)

# =====================================
# График вероятностей состояний
# =====================================

plt.figure(figsize=(12, 6))

plt.bar(
    range(n + 1),
    P
)

plt.title("Предельные вероятности состояний системы Энгсета")
plt.xlabel("Количество неисправных источников")
plt.ylabel("Вероятность")

plt.grid(True)

plt.show()