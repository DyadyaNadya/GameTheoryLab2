import math

# =====================================
# Исходные данные
# =====================================

lam = 4          # заявок в час
t = 1            # мин
k = 18           # каналов
n = 4            # мест в очереди
T = 8            # часов работы
C = 110          # стоимость заявки

# =====================================
# Параметры системы
# =====================================

mu = 60 / t      # обслуживание заявок в час
a = lam / mu     # приведённая нагрузка

# =====================================
# Предельные вероятности состояний (M/M/k/n)
# =====================================

def calc_probs(k, n, a):

    states = k + n
    P = []

    # нормировочная константа
    denom = 0

    for i in range(states + 1):
        if i < k:
            denom += (a ** i) / math.factorial(i)
        else:
            denom += (a ** i) / (math.factorial(k) * (k ** (i - k)))

    P0 = 1 / denom

    for i in range(states + 1):
        if i < k:
            Pi = P0 * (a ** i) / math.factorial(i)
        else:
            Pi = P0 * (a ** i) / (math.factorial(k) * (k ** (i - k)))
        P.append(Pi)

    return P

P = calc_probs(k, n, a)

# =====================================
# Вероятность отказа
# =====================================

P_otk = P[-1]

# =====================================
# Пропускная способность
# =====================================

Q = 1 - P_otk
A = lam * Q

# =====================================
# Средние характеристики
# =====================================

states = len(P) - 1

Lq = sum((i - k) * P[i] for i in range(k, states + 1))
Lq = max(Lq, 0)

L_service = sum(min(i, k) * P[i] for i in range(states + 1))
L = Lq + L_service

W = L / lam
Wq = Lq / lam

# =====================================
# Потери
# =====================================

S_losses = C * lam * P_otk * T

# =====================================
# Вывод результатов
# =====================================

print("\n" + "=" * 70)
print("АНАЛИЗ СМО С ОГРАНИЧЕННОЙ ОЧЕРЕДЬЮ (M/M/k/n)")
print("=" * 70)

print(f"\nИнтенсивность λ = {lam}")
print(f"Интенсивность μ = {mu:.4f}")
print(f"Каналов k = {k}")
print(f"Очередь n = {n}")
print(f"Время работы T = {T} ч")
print(f"Стоимость заявки C = {C}")

print("\n" + "-" * 70)
print("1. ВЕРОЯТНОСТНЫЕ ХАРАКТЕРИСТИКИ")
print("-" * 70)

print(f"Вероятность отказа Pотк = {P_otk:.6f}")
print(f"Относительная пропускная способность Q = {Q:.6f}")
print(f"Абсолютная пропускная способность A = {A:.6f}")

print("\n" + "-" * 70)
print("2. СРЕДНИЕ ХАРАКТЕРИСТИКИ СИСТЕМЫ")
print("-" * 70)

print(f"Среднее число заявок в очереди Lq = {Lq:.6f}")
print(f"Среднее число заявок в обслуживании = {L_service:.6f}")
print(f"Среднее число заявок в системе L = {L:.6f}")

print(f"\nСреднее время ожидания Wq = {Wq:.6f} ч")
print(f"Среднее время в системе W = {W:.6f} ч")

print("\n" + "-" * 70)
print("3. ЭКОНОМИЧЕСКИЕ ПОТЕРИ")
print("-" * 70)

print(f"Потери из-за отказов S = {S_losses:.2f} у.е.")

print("\n" + "=" * 70)